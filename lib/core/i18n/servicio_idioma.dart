import 'package:flutter/material.dart';
import 'package:flutter_riverpod/flutter_riverpod.dart';
import 'package:shared_preferences/shared_preferences.dart';
enum IdiomaApp { es, en }

final idiomaProvider = StateProvider<IdiomaApp>((ref) => ServicioIdioma.inicial);

class _IdiomaHeredado extends InheritedWidget {
  const _IdiomaHeredado({required this.idioma, required super.child});
  final IdiomaApp idioma;
  @override
  bool updateShouldNotify(_IdiomaHeredado old) => idioma != old.idioma;
}

class ServicioIdioma {
  static const _clave = 'fiscogest.idioma';
  static IdiomaApp inicial = IdiomaApp.es;

  static Future<void> preparar() async {
    WidgetsFlutterBinding.ensureInitialized();
    final p = await SharedPreferences.getInstance();
    if (p.getString(_clave) == 'en') inicial = IdiomaApp.en;
  }

  static Widget envolver(BuildContext context, Widget? child) {
    return Consumer(
      builder: (context, ref, _) {
        final idioma = ref.watch(idiomaProvider);
        return _IdiomaHeredado(
          idioma: idioma,
          child: child ?? const SizedBox.shrink(),
        );
      },
    );
  }

  static IdiomaApp actual(BuildContext context) {
    try {
      final heredado = context.dependOnInheritedWidgetOfExactType<_IdiomaHeredado>();
      if (heredado != null) return heredado.idioma;
    } catch (_) {}
    try {
      return ProviderScope.containerOf(context, listen: false).read(idiomaProvider);
    } catch (_) {
      return IdiomaApp.es;
    }
  }

  static Locale localeDe(IdiomaApp idioma) => idioma == IdiomaApp.en
      ? const Locale('en', 'US')
      : const Locale('es', 'DO');

  static String t(BuildContext context, String? texto) {
    final idioma = actual(context);
    if (texto == null) return '';
    if (idioma != IdiomaApp.en) return texto;
    final traduccion = _en[texto];
    if (traduccion != null) return traduccion;
    for (final entrada in _prefijosDinamicos.entries) {
      if (texto.startsWith(entrada.key)) {
        return '${entrada.value}${texto.substring(entrada.key.length)}';
      }
    }
    return texto;
  }

  static Future<void> alternar(BuildContext context) async {
    final caja = ProviderScope.containerOf(context);
    final next = caja.read(idiomaProvider) == IdiomaApp.es ? IdiomaApp.en : IdiomaApp.es;
    caja.read(idiomaProvider.notifier).state = next;

    final p = await SharedPreferences.getInstance();
    await p.setString(_clave, next == IdiomaApp.en ? 'en' : 'es');
  }

  static Widget boton(BuildContext context) {
    final en = actual(context) == IdiomaApp.en;
    return Tooltip(
      message: en ? 'Language' : 'Idioma',
      child: Center(
        child: Padding(
          padding: const EdgeInsets.only(right: 10),
          child: Material(
            color: const Color(0xFF111827),
            elevation: 0,
            borderRadius: BorderRadius.circular(20),
            child: InkWell(
              onTap: () => alternar(context),
              borderRadius: BorderRadius.circular(20),
              child: Container(
                padding: const EdgeInsets.symmetric(horizontal: 12, vertical: 6),
                decoration: BoxDecoration(
                  borderRadius: BorderRadius.circular(20),
                  border: Border.all(color: Colors.white, width: 1.4),
                ),
                child: Text(
                  en ? 'EN' : 'ES',
                  style: const TextStyle(
                    color: Colors.white,
                    fontWeight: FontWeight.w800,
                    fontSize: 13,
                    letterSpacing: 0.4,
                  ),
                ),
              ),
            ),
          ),
        ),
      ),
    );
  }

